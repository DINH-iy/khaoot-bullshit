import { expect, test } from '@playwright/test';
test('room screenshots', async ({ browser, baseURL }) => {
  const hostContext = await browser.newContext({ viewport: { width: 1440, height: 900 } }); const host = await hostContext.newPage();
  const phoneContext = await browser.newContext({ viewport: { width: 412, height: 860 }, isMobile: true, hasTouch: true }); const phone = await phoneContext.newPage();
  const tvContext = await browser.newContext({ viewport: { width: 1600, height: 900 } }); const tv = await tvContext.newPage();
  await host.goto(`${baseURL}/?host=1#owner=${process.env['LOCAL_OWNER_TOKEN']}`);
  await host.getByRole('radio', { name: /Timed quiz/ }).check();
  await host.getByRole('button', { name: 'Open room', exact: true }).click();
  const roomCode = (await host.getByRole('heading', { name: /^Room [A-Z2-9]{6}$/ }).textContent())!.slice(5);
  await host.getByRole('button', { name: 'Create display link' }).click();
  await tv.goto((await host.getByRole('link', { name: 'Open shared display' }).getAttribute('href'))!);
  await phone.goto(`${baseURL}/?code=${roomCode}`);
  await phone.getByLabel('Your name').fill('Dinny');
  await phone.getByRole('button', { name: 'Join room', exact: true }).click();
  await expect(host.getByText('Dinny · connected', { exact: false })).toBeVisible();
  await host.getByRole('button', { name: 'Start the game' }).click();
  await expect(phone.getByRole('radio', { name: 'Saturn', exact: true })).toBeVisible();
  await phone.getByRole('radio', { name: 'Saturn', exact: true }).check();
  await phone.getByRole('button', { name: 'Save answer', exact: true }).click();
  await host.waitForTimeout(500);
  await host.screenshot({ path: '/private/tmp/claude-501/-Users-dinnyvanhuizen-Projects-khaoot-bullshit/2089933f-5674-4005-a8d4-8560f8675101/scratchpad/screens/23-host-question.png' });
  await tv.screenshot({ path: '/private/tmp/claude-501/-Users-dinnyvanhuizen-Projects-khaoot-bullshit/2089933f-5674-4005-a8d4-8560f8675101/scratchpad/screens/24-tv-question.png' });
  await phone.screenshot({ path: '/private/tmp/claude-501/-Users-dinnyvanhuizen-Projects-khaoot-bullshit/2089933f-5674-4005-a8d4-8560f8675101/scratchpad/screens/22-phone-answered.png' });
  await host.getByRole('button', { name: 'Close answers' }).click();
  await host.getByRole('button', { name: 'Reveal results' }).click();
  await tv.waitForTimeout(800);
  await tv.screenshot({ path: '/private/tmp/claude-501/-Users-dinnyvanhuizen-Projects-khaoot-bullshit/2089933f-5674-4005-a8d4-8560f8675101/scratchpad/screens/25-tv-results.png' });
  for (const context of [hostContext, phoneContext, tvContext]) await context.close();
});
