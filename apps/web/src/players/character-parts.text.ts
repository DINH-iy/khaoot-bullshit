const NONE: Partial<Record<LookPart, 'noHat' | 'noBeard' | 'noPiercing'>> = { hat: 'noHat', beard: 'noBeard', piercing: 'noPiercing' };
export function partName(part: LookPart, value: PlayerLook[LookPart]): string {
  const key = value === undefined || value === 'none' ? NONE[part] ?? 'nothing' : value;
  return translate(PART_TEXTS, key);
}

export function describeLook(look: PlayerLook): string {
  if (look.picture) return translate(PART_TEXTS, look.picture.kind === 'photo' ? 'aPhoto' : 'aDrawing');
  const lowerUnlessGerman = (text: string) => currentLanguage() === 'de' ? text : text.toLocaleLowerCase(currentLanguage());
  const body = lowerUnlessGerman(partName('body', look.body));
  const hat = look.hat === 'none' ? '' : lowerUnlessGerman(partName('hat', look.hat));
  const extra = look.extra === 'none' ? '' : lowerUnlessGerman(partName('extra', look.extra));
  if (hat && extra) return translate(PART_TEXTS, 'withBoth', { body, hat, extra });
  if (hat) return translate(PART_TEXTS, 'withHat', { body, hat });
  if (extra) return translate(PART_TEXTS, 'withExtra', { body, extra });
  return body;
}
